import { expect, test, type Page } from '@playwright/test'

const root = process.env.DB151_QA_URL
async function openShop(page: Page, scenario: 'busy' | 'quiet' | 'clear') {
  const password = process.env.DB151_OWNER_PASSWORD
  test.skip(!root || !password, 'Requires the local DB151 QA shops')
  expect(new URL(root!).hostname).toBe('127.0.0.1')
  await page.goto(`${root}/dashboard`)
  await page.locator('input[type=email]').fill(`db151-${scenario}@example.com`)
  await page.locator('input[type=password]').fill(password!)
  await page.getByRole('button', { name: /^Sign in$/i }).click()
  await expect(page.getByRole('heading', { name: 'Needs your attention' })).toBeVisible()
}
const tab = (page: Page, label: string) => page.getByRole('button', { name: new RegExp(`^${label}(?: |$)`) })
const record = (page: Page, number: string) => page.getByRole('heading', { name: `#${number}`, exact: true })

test('quiet shop: all four views open exact records at desk and phone widths', async ({ page }) => {
  test.setTimeout(180_000)
  await openShop(page, 'quiet')
  for (const width of [1440, 390]) {
    // Both passes use the same local API principal; respect its minute read window.
    if (width === 390) await new Promise(resolve => setTimeout(resolve, 65_000))
    await page.setViewportSize({ width, height: 850 })
    await tab(page, 'Overview').click()
    const stock = page.getByRole('link', { name: /^Review stock:/ })
    const core = page.getByRole('link', { name: /^Review core return:/ })
    for (const [link, kind] of [[stock, 'inventory'], [core, 'purchasing']] as const) {
      const href = await link.getAttribute('href')
      expect(href).toContain(`/garage/${kind}?`)
      await link.click()
      await expect(page).toHaveURL(root! + href)
      await expect(page.getByText('DB151 Brake chamber T30', { exact: true }).filter({ visible: true }).first()).toBeVisible()
      await page.goBack()
      await expect(link).toBeFocused()
    }
    await tab(page, 'Active work').click()
    const quiet = page.getByRole('region', { name: 'Active work aging' })
    await expect(quiet.getByText('No active jobs in this view')).toBeVisible()
    await expect(quiet.getByRole('searchbox')).toHaveCount(0)
    const next = quiet.getByRole('link', { name: 'Review closeout: DB151-quiet-1049' })
    await next.click()
    await expect(record(page, 'DB151-quiet-1049')).toBeVisible()
    await page.getByRole('button', { name: 'Close repair order', exact: true }).click()
    await expect(next).toBeVisible()
    await tab(page, 'Closeout').click()
    await expect(page.getByText('Ready to Close · 2')).toBeVisible()
    await expect(page.getByRole('tablist', { name: 'Work queues' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Open DB151-quiet-1049 in Repair Orders' }).click()
    await expect(record(page, 'DB151-quiet-1049')).toBeVisible()
    await page.goBack()
    await expect(page.getByText('Ready to Close · 2')).toBeVisible()
    await tab(page, 'Activity').click()
    await expect(page.getByRole('button', { name: 'Activity', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: /^Activity filters/ }).click()
    await page.getByRole('button', { name: 'Activity type' }).click()
    await page.getByRole('option', { name: 'Invoice created', exact: true }).click()
    await page.getByRole('button', { name: 'Close activity filters' }).click()
    const event = page.getByRole('link', { name: 'Invoice created: open repair order DB151-quiet-1048' })
    await event.click()
    await expect(record(page, 'DB151-quiet-1048')).toBeVisible()
    await page.getByRole('button', { name: 'Close repair order', exact: true }).click()
    await expect(event).toBeVisible()
    await expect(page.getByRole('button', { name: 'Activity filters, 1 applied' })).toBeVisible()
    await page.reload()
    await expect(event).toBeVisible()
    await page.getByRole('button', { name: /^Activity filters/ }).click()
    await page.getByRole('button', { name: 'Activity type' }).click()
    await page.getByRole('option', { name: 'Quote sent', exact: true }).click()
    await page.getByRole('button', { name: 'Close activity filters' }).click()
    await page.getByRole('button', { name: 'Clear activity filters' }).click()
    await expect(page.getByRole('link', { name: /^Work completed: open repair/ }).first()).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})

test('busy shop: nonempty active categories and a filtered miss remain recoverable', async ({ page }) => {
  await openShop(page, 'busy')
  await tab(page, 'Active work').click()
  const search = page.getByRole('searchbox', { name: 'Search active work' })
  const work = page.getByRole('button', { name: 'Open DB151-busy-1062 in Shop Work' })
  await expect(work).toBeVisible()
  await search.fill('missing-order-zz')
  await page.getByRole('button', { name: 'Clear search and filters' }).click()
  await expect(work).toBeVisible()
  await work.click()
  await expect(record(page, 'DB151-busy-1062')).toBeVisible()
  await page.goBack()
  await expect(work).toBeVisible()
})

test('clear shop: empty Active work never suggests a nonexistent record', async ({ page }) => {
  await openShop(page, 'clear')
  await tab(page, 'Active work').click()
  await page.getByRole('link', { name: 'View shop overview' }).click()
  await expect(page.locator('.db-overview__empty')).toBeVisible()
  await expect(page.locator('.db-overview__task')).toHaveCount(0)
  await tab(page, 'Closeout').click()
  await expect(page.getByText('No closeout work in this queue')).toBeVisible()
  await expect(page.getByRole('searchbox', { name: 'Search work queue' })).toHaveCount(0)
})
