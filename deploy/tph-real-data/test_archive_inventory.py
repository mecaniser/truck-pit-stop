class Int32(int):
    pass


def string(value):
    raw = value.encode() + b'\0'
    return struct.pack('<i', len(raw)) + raw


def document(fields):
    raw = b''
    pairs = fields.items() if isinstance(fields, dict) else fields
    for key, value in pairs:
        if isinstance(value, bool): kind, encoded = 8, bytes([value])
        elif isinstance(value, Int32): kind, encoded = 16, struct.pack('<i', value)
        elif isinstance(value, str): kind, encoded = 2, string(value)
        elif isinstance(value, int): kind, encoded = 18, struct.pack('<q', (value + 2**63) % 2**64 - 2**63)
        elif isinstance(value, dict): kind, encoded = 3, document(value)
        elif value is None: kind, encoded = 10, b''
        else: raise AssertionError('fixture type not supported')
        raw += bytes([kind]) + key.encode() + b'\0' + encoded
    return struct.pack('<i', len(raw) + 5) + raw + b'\0'


def prelude(collections):
    header = {'version': '0.1', 'concurrent_collections': Int32(4), 'server_version': '7.0.0', 'tool_version': '100.11.0'}
    raw = inv.MAGIC + document(header)
    for name, _ in collections.items():
        metadata = {'options': {}, 'indexes': [{'v': {'$numberInt': '2'}, 'key': {'_id': {'$numberInt': '1'}}, 'name': '_id_'}], 'uuid': 'fixture-only'}
        raw += document({'db': 'ParkRightDB', 'collection': name, 'metadata': json.dumps(metadata), 'size': 0, 'type': 'collection'})
    return raw + inv.END


def block(name, docs=(), eof=False, crc=0):
    return document({'db': 'ParkRightDB', 'collection': name, 'EOF': eof, 'CRC': crc}) + b''.join(docs) + inv.END


def archive(collections, interleave=False):
    raw = prelude(collections)
    if interleave:
        # Multiple data blocks per namespace and interleaving are legal.
        for i in range(max((len(v) for v in collections.values()), default=0)):
            for name, docs in collections.items():
                if i < len(docs): raw += block(name, [docs[i]])
        for name, docs in collections.items(): raw += block(name, eof=True, crc=inv.crc64(b''.join(docs)))
    else:
        for name, docs in collections.items():
            raw += block(name, docs) + block(name, eof=True, crc=inv.crc64(b''.join(docs)))
    return raw


class ArchiveTests(unittest.TestCase):
    def setUp(self):
        self.docs = [document({'_id': 1, 'name': 'PRIVATE_SENTINEL_NEVER_OUTPUT'}), document({'_id': 2, 'active': True})]

    def test_go_official_crc64_ecma_golden_vectors_and_incremental(self):
        # golang/go src/hash/crc64/crc64_test.go golden vectors, not generated by our encoder.
        self.assertEqual(inv.crc64(b''), 0)
        self.assertEqual(inv.crc64(b'a'), 0x330284772e652b05)
        self.assertEqual(inv.crc64(b'abc'), 0x2cd8094a1a277627)
        self.assertEqual(inv.crc64(b'c', inv.crc64(b'ab')), 0x2cd8094a1a277627)

    def test_interleaved_empty_and_exact_raw_multiset(self):
        result = inv.inventory_stream(io.BytesIO(archive({'pins': self.docs, 'empty': []}, interleave=True)))
        ns = result['namespaces']['ParkRightDB.pins']
        self.assertEqual(ns['count'], 2)
        self.assertEqual(ns['bson_bytes'], sum(map(len, self.docs)))
        hashes = Counter(__import__('hashlib').sha256(d).digest() for d in self.docs)
        self.assertEqual(ns['documents_sha256'], inv.document_fingerprint(hashes))
        self.assertEqual(result['namespaces']['ParkRightDB.empty']['count'], 0)
        self.assertTrue(result['namespace_crc_verified'])
        self.assertNotIn('PRIVATE_SENTINEL', json.dumps(result))

    def test_order_independent_but_duplicates_types_and_field_order_preserved(self):
        def fp(docs): return inv.inventory_stream(io.BytesIO(archive({'pins': docs})))['namespaces']['ParkRightDB.pins']['documents_sha256']
        self.assertEqual(fp(self.docs), fp(list(reversed(self.docs))))
        self.assertNotEqual(fp(self.docs), fp(self.docs + [self.docs[0]]))
        self.assertNotEqual(fp([document([('a', 1), ('b', 2)])]), fp([document([('b', 2), ('a', 1)])]))
        self.assertNotEqual(fp([document({'a': 1})]), fp([document({'a': '1'})]))
        # Duplicate body keys are retained in raw BSON; never collapsed into a Python dictionary.
        self.assertNotEqual(fp([document([('a', 1), ('a', 2)])]), fp([document({'a': 2})]))

    def test_corruption_and_crc_fail_closed(self):
        good = archive({'pins': self.docs})
        variants = [b'WRNG' + good[4:], good[:-1], good + b'bad', good[:50],
                    prelude({'pins': []}) + block('pins', self.docs) + block('pins', eof=True, crc=1),
                    prelude({'pins': []}) + block('pins', self.docs),
                    prelude({'pins': []}) + block('foreign', self.docs),
                    prelude({'pins': []}) + inv.END,
                    prelude({'pins': []}) + block('pins', eof=True) + block('pins'),
                    prelude({'pins': []}) + block('pins', eof=True)[:-4] + self.docs[0] + inv.END]
        for raw in variants:
            with self.subTest(case=variants.index(raw)), self.assertRaises(inv.Refused):
                inv.inventory_stream(io.BytesIO(raw))

    def test_control_bson_numeric_types_and_official_size_bound(self):
        header = {'version': '0.1', 'concurrent_collections': 4, 'server_version': '7.0', 'tool_version': '100.11'}
        with self.assertRaisesRegex(inv.Refused, 'archive_header_refused'):
            inv.inventory_stream(io.BytesIO(inv.MAGIC + document(header) + inv.END))
        raw = prelude({'pins': []}) + document({'db': 'ParkRightDB', 'collection': 'pins', 'EOF': True, 'CRC': Int32(0)}) + inv.END
        with self.assertRaisesRegex(inv.Refused, 'namespace_header_schema'):
            inv.inventory_stream(io.BytesIO(raw))
        self.assertEqual(inv.MAX_BSON, 16 * 1024 * 1024)
        with self.assertRaisesRegex(inv.Refused, 'archive_bson_length_invalid'):
            inv.Stream(io.BytesIO(struct.pack('<i', inv.MAX_BSON + 1))).frame()

    def test_duplicate_namespace_and_control_keys_refused(self):
        metadata = document({'db': 'ParkRightDB', 'collection': 'pins', 'metadata': '{"indexes":[]}'})
        raw = prelude({})[:-4] + metadata + metadata + inv.END
        with self.assertRaisesRegex(inv.Refused, 'duplicate_or_excess_namespace'):
            inv.inventory_stream(io.BytesIO(raw))
        with self.assertRaisesRegex(inv.Refused, 'duplicate_control_field'):
            inv.bson(document([('db', 'ParkRightDB'), ('db', 'other')]))
        with self.assertRaisesRegex(inv.Refused, 'duplicate_json_field'):
            inv.json_metadata('{"indexes":[],"indexes":[]}')

    def test_credential_scan_never_outputs_keys_paths_or_values(self):
        raw = document({'provider': {'JohnPrivateName': {'apiKey': 'SECRET_VALUE_NOT_OUTPUT'}},
                        'pinHash': 'HASH_NOT_OUTPUT'})
        result = inv.inventory_stream(io.BytesIO(archive({'pins': [raw]})), scan_keys=True)
        findings = result['namespaces']['ParkRightDB.pins']['credential_key_findings']
        self.assertEqual(len(findings), 2)
        output = json.dumps(result)
        for forbidden in ('JohnPrivateName', 'SECRET_VALUE_NOT_OUTPUT', 'HASH_NOT_OUTPUT', 'apiKey', 'pinHash'):
            self.assertNotIn(forbidden, output)
        self.assertEqual({f['category'] for f in findings}, {'credential_key', 'auth_capability_key'})

    def test_indexes_compound_key_order_and_all_spec_options_checked(self):
        def metadata(key, **extra): return {'options': {}, 'indexes': [{'v': 2, 'name': 'compound', 'key': key, **extra}]}
        one = inv.fingerprints(metadata({'a': 1, 'b': -1}), 'ParkRightDB.pins')
        two = inv.fingerprints(metadata({'b': -1, 'a': 1}), 'ParkRightDB.pins')
        self.assertNotEqual(one['indexes_sha256'], two['indexes_sha256'])
        self.assertNotEqual(one['indexes_sha256'], inv.fingerprints(metadata({'a': 1, 'b': -1}, unique=True), 'ParkRightDB.pins')['indexes_sha256'])
        with self.assertRaises(inv.Refused):
            inv.fingerprints(metadata({'a': 1}, ns='production.other'), 'ParkRightDB.pins')

    def test_gzip_crc_sha_private_receipt_and_no_overwrite(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp).resolve()
            root.chmod(0o700)
            file = root / 'synthetic.archive.gz'
            file.write_bytes(gzip.compress(archive({'pins': self.docs})))
            file.chmod(0o600)
            result = inv.inventory_file(file, inv.sha(file.read_bytes()))
            self.assertTrue(result['gzip_crc_verified'])
            receipt = root / 'inventory.json'
            inv.write_private(receipt, result)
            self.assertEqual(receipt.stat().st_mode & 0o777, 0o600)
            with self.assertRaises(FileExistsError): inv.write_private(receipt, result)
            with self.assertRaisesRegex(inv.Refused, 'archive_sha_mismatch'): inv.inventory_file(file, '0' * 64)
            data = bytearray(file.read_bytes());data[-8] ^= 1;file.write_bytes(data)
            with self.assertRaisesRegex(inv.Refused, 'gzip_integrity'): inv.inventory_file(file, inv.sha(data))

    def test_compare_requires_every_document_index_option_and_namespace(self):
        source = inv.inventory_stream(io.BytesIO(archive({'pins': self.docs})))
        target = copy.deepcopy(source)
        self.assertTrue(inv.compare(source, target)['matches'])
        for field in ('count', 'bson_bytes', 'documents_sha256', 'indexes_sha256', 'index_count', 'collection_options_sha256'):
            changed = copy.deepcopy(target)
            changed['namespaces']['ParkRightDB.pins'][field] = 'changed'
            with self.assertRaises(inv.Refused): inv.compare(source, changed)
        target['namespaces']['foreign'] = {}
        with self.assertRaises(inv.Refused): inv.compare(source, target)

    def test_bson_malformed_types_nested_sizes_binary_and_code_scope(self):
        for body in (b'\x08x\0\x02', b'\x42x\0', b'\x02x\0' + struct.pack('<i', -1),
                     b'\x03x\0' + struct.pack('<i', 100), b'\x05x\0' + struct.pack('<i', -1) + b'\0',
                     b'\x0fx\0' + struct.pack('<i', 14) + b'\0' * 10):
            raw = struct.pack('<i', len(body) + 5) + body + b'\0'
            with self.assertRaises(inv.Refused): inv.bson(raw, decode=False)

    def test_metadata_number_key_ambiguity_requires_review(self):
        with self.assertRaisesRegex(inv.Refused, 'metadata_numeric_key_requires_review'):
            inv.fingerprints({'indexes': [{'name': 'numeric-fields', 'key': {'2': 1, '1': 1}}]}, 'ParkRightDB.pins')

    def test_bson_supported_types_and_array_key_validation(self):
        # Independently construct every BSON1.1 element type, including deprecated
        # binary/DBPointer/JS-with-scope. Values are synthetic and never emitted.
        empty = document({})
        code_scope = struct.pack('<i', 4 + len(string('x')) + len(empty)) + string('x') + empty
        types = {1: struct.pack('<d', 1.25), 2: string('text'), 3: empty, 4: document({'0': 'entry'}),
                 5: struct.pack('<i', 7) + b'\x02' + struct.pack('<i', 3) + b'abc',
                 6: b'', 7: b'x' * 12, 8: b'\x01', 9: b'\0' * 8, 10: b'',
                 11: b'x\0i\0', 12: string('namespace') + b'x' * 12, 13: string('code'),
                 14: string('symbol'), 15: code_scope, 16: b'\0' * 4, 17: b'\0' * 8,
                 18: b'\0' * 8, 19: b'\0' * 16, 127: b'', 255: b''}
        for kind, value in types.items():
            with self.subTest(kind=kind):
                body = bytes([kind]) + b'field\0' + value
                inv.bson(struct.pack('<i', len(body) + 5) + body + b'\0', decode=False)
        body = b'\x04field\0' + document({'1': 'invalid-first-index'})
        with self.assertRaisesRegex(inv.Refused, 'bson_array_keys_invalid'):
            inv.bson(struct.pack('<i', len(body) + 5) + body + b'\0', decode=False)

